/**
 * Renders the generated compatibility scoreboard (docs/compat.md).
 *
 * Pure string building — the CLI writes the result. The document carries the
 * full evidence chain: how the run was performed, every failure with its
 * one-line reason, the by-design errors, and the owner's Tier 3 checklist.
 */

import type { CompatPluginReport, CompatReport } from "./report";

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

/**
 * The explanation column. A hand-written diagnosis always leads when one
 * exists, but the measured reason is kept next to it — the scoreboard explains
 * itself without dropping the evidence the run produced.
 */
function reasonCell(plugin: CompatPluginReport): string {
  const measured = plugin.reason;
  if (plugin.diagnosis === null) return measured === null ? "—" : escapeCell(measured);
  if (measured === null) return escapeCell(plugin.diagnosis);
  return `${escapeCell(plugin.diagnosis)} — measured: ${escapeCell(measured)}`;
}

function verdictCell(verdict: "pass" | "fail" | "not-run"): string {
  if (verdict === "fail") return "**fail**";
  if (verdict === "not-run") return "not run";
  return "pass";
}

function statusCell(status: CompatReport["plugins"][number]["status"]): string {
  if (status === "fail") return "**fail**";
  return status;
}

/** The scoreboard document for one analysis run. */
export function renderCompatMarkdown(report: CompatReport): string {
  const lines: string[] = [];
  const { meta, summary, run } = report;
  const label = meta.ecosystem === "bd" ? "BetterDiscord" : "Vencord";

  lines.push("# Compatibility scoreboard");
  lines.push("");
  lines.push(
    "> Generated by `@ion/compat-harness` (`pnpm --filter @ion/compat-harness report`). " +
      "Do not edit by hand — rerun the harness instead.",
  );
  lines.push("");
  lines.push(
    `Generated ${report.generatedAt} · ${label} source ${meta.upstream} · ` +
      `session: ${meta.session} · soak: ${String(Math.round(meta.soakMs / 1000))}s ` +
      `(${meta.tier2Run ? "Tier 2 measured" : "below the Tier 2 soak minimum"})`,
  );
  lines.push("");
  lines.push(`## ${label} acceptance set`);
  lines.push("");
  lines.push(
    `${String(summary.total)} plugins · **${String(summary.pass)} pass** · ` +
      `${String(summary.warnings)} pass with warnings · ${String(summary.fail)} fail · ` +
      `${String(summary.deferred)} deferred`,
  );
  lines.push("");
  lines.push(
    "| Plugin | Group | Tier 1 (load) | Tier 2 (soak) | Status | Reason / notes | Tier 3: check by hand |",
  );
  lines.push("| --- | --- | --- | --- | --- | --- | --- |");
  for (const plugin of report.plugins) {
    const hand = escapeCell(plugin.handCheck);
    lines.push(
      `| ${escapeCell(plugin.name)} | ${plugin.group} | ${verdictCell(plugin.tier1)} ` +
        `| ${verdictCell(plugin.tier2)} | ${statusCell(plugin.status)} | ${reasonCell(plugin)} ` +
        `| ${hand} |`,
    );
  }
  lines.push("");

  lines.push("## Run evidence");
  lines.push("");
  lines.push(
    `- Plugins registered: ${String(run.registered)} · started: ${String(run.started)} · ` +
      `failed: ${String(run.failed)}`,
  );
  lines.push(
    `- Patches: ${String(run.patchTotals.registered)} registered, ` +
      `${String(run.patchTotals.applied)} applied so far, ` +
      `${String(run.patchTotals.active)} still active — unmatched patches wait for their ` +
      "target module to evaluate (a logged-out session leaves most of Discord's modules " +
      "unevaluated), and `all` patches keep watching after applying",
  );
  if (run.rendererErrors.length === 0) {
    lines.push("- Renderer errors: none");
  } else {
    lines.push(`- Renderer errors (${String(run.rendererErrors.length)}):`);
    for (const error of run.rendererErrors) lines.push(`  - ${escapeCell(error)}`);
  }
  if (run.expectedErrors.length > 0) {
    lines.push("- Errors that are by design of the bundled software:");
    for (const expected of run.expectedErrors) {
      lines.push(`  - ${escapeCell(expected.reason)} (×${String(expected.count)})`);
    }
  }
  if (run.unattributedWarnings.length > 0) {
    lines.push("- Warnings not attributable to a single plugin:");
    for (const warning of run.unattributedWarnings) lines.push(`  - ${escapeCell(warning)}`);
  }
  lines.push("");

  lines.push("## Method");
  lines.push("");
  lines.push(
    "- **Tier 1 (automated)**: the plugin registers with the host, `start()` does not throw, " +
      "and none of its source patches fail. Measured from the end-of-run snapshot, which " +
      "subsumes load time: failed starts never retry and patch notices are cumulative, so a " +
      "late patch failure is conservatively counted here.",
  );
  lines.push(
    "- **Tier 2 (automated)**: with all acceptance plugins enabled, the session soaks for the " +
      "window above in a read-only state; no uncaught error is attributable to the plugin and " +
      "no patch of its fails. A pass is only claimed when the soak reached " +
      '120s; shorter runs report "not run".',
  );
  lines.push(
    "- **Tier 3 (owner, pending)**: the last column is the checklist — run each line by hand " +
      "on a logged-in session. Nothing in this document is Tier-3-verified.",
  );
  lines.push(
    "- Environment: fresh isolated profile, no login (`--ion-profile`), hidden offscreen " +
      "window, idle I/O priority. Read-only: no messages, joins, or account changes.",
  );
  lines.push("");

  return `${lines.join("\n")}\n`;
}

import { describe, expect, test } from "vitest";

import { renderCompatMarkdown } from "./markdown";
import { analyze, type AcceptanceEntry, TIER2_MIN_SOAK_MS } from "./report";

const ACCEPTANCE: readonly AcceptanceEntry[] = [
  {
    group: "D",
    folder: "petpet",
    name: "petpet",
    tier3: "Right-click a user → Pet Pet: image must send.",
  },
  { group: "D", folder: "fakeNitro", name: "FakeNitro", tier3: "Emoji picker check." },
];

function report() {
  return analyze(
    {
      session: "logged-out",
      settleMs: TIER2_MIN_SOAK_MS,
      pluginsStatus: {
        status: { registered: 2, started: 2, failed: 0 },
        ids: ["petpet:started", "FakeNitro:started"],
        failures: [],
      },
      rendererErrors: [],
      expectedErrors: { "NoTrack deliberately aborts Sentry's module evaluation": 1 },
      warnings: ["[petpet] something | with a pipe"],
      patchStats: {},
    },
    ACCEPTANCE,
    {
      generatedAt: "2026-10-12T00:00:00.000Z",
      ecosystem: "vencord",
      upstream: "1.15.11 (16ec4ea)",
    },
  );
}

describe("renderCompatMarkdown", () => {
  const markdown = renderCompatMarkdown(report());

  test("carries the generated-by banner and run metadata", () => {
    expect(markdown).toContain("Generated by `@ion/compat-harness`");
    expect(markdown).toContain("Vencord source 1.15.11 (16ec4ea)");
    expect(markdown).toContain("Tier 2 measured");
  });

  test("lists every plugin with its tiers and hand check", () => {
    expect(markdown).toContain("| petpet | D | pass | pass | warnings |");
    expect(markdown).toContain("Right-click a user → Pet Pet: image must send.");
    expect(markdown).toContain("| FakeNitro | D | pass | pass | pass | — | Emoji picker check. |");
  });

  test("escapes pipes in reasons and shows the summary line", () => {
    expect(markdown).toContain("something \\| with a pipe");
    expect(markdown).toContain(
      "2 plugins · **1 pass** · 1 pass with warnings · 0 fail · 0 deferred",
    );
  });

  test("records by-design errors as evidence", () => {
    expect(markdown).toContain("by design");
    expect(markdown).toContain("×1");
  });

  test("ends with the method section that keeps Tier 3 marked pending", () => {
    expect(markdown).toContain("## Method");
    expect(markdown).toContain("Nothing in this document is Tier-3-verified.");
  });

  test("leads a failure with its diagnosis but keeps the measured reason", () => {
    const failed = renderCompatMarkdown(
      analyze(
        {
          session: "logged-out",
          settleMs: TIER2_MIN_SOAK_MS,
          pluginsStatus: {
            status: { registered: 2, started: 0, failed: 2 },
            ids: ["bd.BetterFolders:failed", "bd.LiveTyping:failed"],
            failures: [
              { id: "bd.BetterFolders", error: "Cannot read properties of undefined" },
              { id: "bd.LiveTyping", error: "Cannot set property A" },
            ],
          },
          rendererErrors: [],
          expectedErrors: {},
          warnings: [],
          patchStats: {},
        },
        [
          {
            group: "A",
            name: "BetterFolders",
            id: "bd.BetterFolders",
            diagnosis: "Needs a signed-in session to measure.",
          },
          { group: "A", name: "LiveTyping", id: "bd.LiveTyping" },
        ],
        {
          generatedAt: "2026-10-13T00:00:00.000Z",
          ecosystem: "bd",
          upstream: "133bc83 (Apache-2.0 port of BdApi)",
        },
      ),
    );

    // The explanation leads, but the run's own evidence stays attached to it.
    expect(failed).toContain("Needs a signed-in session to measure. — measured: start failed:");
    // With no diagnosis the measured reason is the whole cell, as before.
    expect(failed).toContain("start failed: Cannot set property A |");
  });

  test("titles a BetterDiscord report with its own ecosystem labels", () => {
    const bd = renderCompatMarkdown(
      analyze(
        {
          session: "logged-out",
          settleMs: TIER2_MIN_SOAK_MS,
          pluginsStatus: {
            status: { registered: 1, started: 1, failed: 0 },
            ids: ["bd.BlurNSFW:started"],
            failures: [],
          },
          rendererErrors: [],
          expectedErrors: {},
          warnings: [],
          patchStats: {},
        },
        [{ group: "A", name: "BlurNSFW", id: "bd.BlurNSFW" }],
        {
          generatedAt: "2026-10-12T00:00:00.000Z",
          ecosystem: "bd",
          upstream: "133bc83 (Apache-2.0 port of BdApi)",
        },
      ),
    );
    expect(bd).toContain("## BetterDiscord acceptance set");
    expect(bd).toContain("BetterDiscord source 133bc83");
  });
});
